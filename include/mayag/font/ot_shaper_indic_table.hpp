inline constexpr std::uint16_t default_value = 3584;   // _(X, X): category X, POS_END

inline std::uint16_t get_categories(char32_t u) noexcept {
    const Range* it = std::upper_bound(std::begin(ranges), std::end(ranges), u,
                                       [](char32_t c, const Range& r) { return c < r.first; });
    if (it == std::begin(ranges)) return default_value;
    --it;
    return u <= it->last ? it->value : default_value;
}

