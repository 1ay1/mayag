// apple_stems.c — generate include/mayag/font/apple_stems.hpp: every
// installed font's horizontal stem as CoreGraphics' autohinter sees it.
//
// CGFontAutohintTransformCreate bounds the cap band it moves as a block by
// the font's stemH, which libFontParser serves from the font registry's
// metadata (StdHW for CFF fonts; a registry measurement for TrueType), not
// from any table mayag can parse. CoreGraphics rescales it to a 1000-unit
// em, round(stemH * 1000 / upem), and then uses it as font units; the table
// stores that value. Fonts without one (SF, Arial, ... 0) are left out.
//
//   clang -O1 tools/apple_stems.c -o /tmp/apple_stems \
//       -framework ApplicationServices -framework CoreText
//   /tmp/apple_stems > include/mayag/font/apple_stems.hpp
#include <ApplicationServices/ApplicationServices.h>
#include <CoreText/CoreText.h>
#include <dlfcn.h>
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

extern void* CGFontGetParserFont(CGFontRef);

typedef struct { char name[128]; int stem; } Entry;
static int cmp(const void* a, const void* b) { return strcmp(((const Entry*)a)->name, ((const Entry*)b)->name); }

static Entry* entries; static size_t count, cap_;
static int (*stem_h)(void*);

static void add(CTFontDescriptorRef d) {
    CTFontRef f = CTFontCreateWithFontDescriptor(d, 12, NULL);
    if (!f) return;
    CGFontRef cg = CTFontCopyGraphicsFont(f, NULL);
    CFStringRef ps = CGFontCopyPostScriptName(cg);
    char b[128];
    if (ps && CFStringGetCString(ps, b, sizeof b, kCFStringEncodingUTF8)) {
        for (size_t i = 0; i < count; ++i) if (!strcmp(entries[i].name, b)) goto done;
        void* fp = CGFontGetParserFont(cg);
        int upem = CGFontGetUnitsPerEm(cg), sh = fp ? stem_h(fp) : 0;
        int s = upem > 0 ? (int)round((double)sh * 1000.0 / upem) : 0;
        if (s > 0) {
            if (count == cap_) { cap_ = cap_ ? cap_ * 2 : 256; entries = realloc(entries, cap_ * sizeof *entries); }
            strcpy(entries[count].name, b); entries[count].stem = s; ++count;
        }
    }
done:
    if (ps) CFRelease(ps);
    CGFontRelease(cg); CFRelease(f);
}

static void scan(const char* path) {
    CFURLRef dir = CFURLCreateFromFileSystemRepresentation(NULL, (const UInt8*)path, (CFIndex)strlen(path), true);
    CFURLEnumeratorRef en = CFURLEnumeratorCreateForDirectoryURL(NULL, dir, kCFURLEnumeratorDescendRecursively, NULL);
    CFURLRef u;
    while (CFURLEnumeratorGetNextURL(en, &u, NULL) == kCFURLEnumeratorSuccess) {
        CFArrayRef ds = CTFontManagerCreateFontDescriptorsFromURL(u);
        if (!ds) continue;
        for (CFIndex i = 0; i < CFArrayGetCount(ds); ++i) add(CFArrayGetValueAtIndex(ds, i));
        CFRelease(ds);
    }
    CFRelease(en); CFRelease(dir);
}

int main(void) {
    void* h = dlopen("/System/Library/PrivateFrameworks/FontServices.framework/libFontParser.dylib", RTLD_NOW);
    stem_h = (int (*)(void*))dlsym(h ? h : RTLD_DEFAULT, "FPFontGetStemH");
    if (!stem_h) { fprintf(stderr, "FPFontGetStemH not found\n"); return 1; }
    scan("/System/Library/Fonts");
    scan("/Library/Fonts");
    scan("/System/Library/PrivateFrameworks/FontServices.framework/Resources/Reserved");
    qsort(entries, count, sizeof *entries, cmp);
    printf("// Generated by tools/apple_stems.c from this Mac's font registry: the\n"
           "// stemH CoreGraphics' autohinter uses per font (round(stemH*1000/upem),\n"
           "// which CoreGraphics then treats as font units). Do not edit by hand.\n"
           "#pragma once\n\n#include <algorithm>\n#include <cstdint>\n#include <iterator>\n#include <string_view>\n\n"
           "namespace mayag::typo::apple {\n\n"
           "struct StemEntry { std::string_view name; std::uint16_t stem; };\n\n"
           "inline constexpr StemEntry autohint_stems[] = {\n");
    for (size_t i = 0; i < count; ++i) printf("    {\"%s\", %d},\n", entries[i].name, entries[i].stem);
    printf("};\n\n"
           "/// The autohint stem for a PostScript name; 0 when the registry has none.\n"
           "[[nodiscard]] inline std::uint16_t autohint_stem(std::string_view ps_name) noexcept {\n"
           "    const auto* b = std::begin(autohint_stems);\n"
           "    const auto* e = std::end(autohint_stems);\n"
           "    const auto* it = std::lower_bound(b, e, ps_name, [](const StemEntry& s, std::string_view n) { return s.name < n; });\n"
           "    return it != e && it->name == ps_name ? it->stem : 0;\n"
           "}\n\n}  // namespace mayag::typo::apple\n");
    return 0;
}
