#!/usr/bin/env python3
"""font_fingerprints.py OUT FILE... : write "PATH SIZE FNV1A64" per font file.

Shaping expectations and CoreText measurements are captured from specific
font FILES. Another macOS release ships different builds of the same paths
(SF on macOS 15 renumbers its glyphs), so tests skip cases whose installed
file differs from the one the data was captured from. Keep in sync with
mayag::test::font_fingerprint (tests/font_fingerprint.hpp).
"""
import sys


def fnv1a64(path):
    # Size plus the first and last 64 KB: enough to tell two builds of a font
    # apart (the table directory and head checksum live up front), cheap
    # enough for 100 MB collections.
    h = 0xcbf29ce484222325
    with open(path, 'rb') as f:
        f.seek(0, 2)
        n = f.tell()
        f.seek(0)
        data = f.read(65536)
        if n > 131072:
            f.seek(n - 65536)
        else:
            f.seek(min(n, 65536))
        data += f.read(65536)
    for b in data:
        h ^= b
        h = (h * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return n, h


def main():
    out = sys.argv[1]
    lines = ["# PATH SIZE FNV1A64 -- generated by tools/font_fingerprints.py; do not edit"]
    for p in sorted(set(sys.argv[2:])):
        try:
            n, h = fnv1a64(p)
        except OSError:
            continue
        lines.append("%s %d %016x" % (p, n, h))
    with open(out, 'w') as f:
        f.write("\n".join(lines) + "\n")


if __name__ == '__main__':
    main()
