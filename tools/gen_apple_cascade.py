#!/usr/bin/env python3
# gen_apple_cascade.py ORDER.txt OUT.hpp
#
# ORDER.txt is the flat fallback order derived from CoreText (one line per
# face: postscript<TAB>face_index<TAB>path), produced by
#   clang -O2 -framework CoreText -framework CoreFoundation tools/ct_cascade2.c -o /tmp/ct_cascade2
#   python3 -c "<print every assigned codepoint in hex>" | /tmp/ct_cascade2 > /tmp/ct_all.txt
#   python3 tools/derive_cascade.py 5 > ORDER.txt      (needs fontTools)
import sys, json, os
rows = [l.rstrip('\n').split('\t') for l in open(sys.argv[1], encoding='utf-8') if l.strip()]
limits = json.load(open(sys.argv[3])) if len(sys.argv) > 3 and os.path.exists(sys.argv[3]) else {}
out = open(sys.argv[2], 'w', encoding='utf-8')
out.write('''#pragma once
// apple_cascade.hpp — the macOS UI font's fallback order, measured.
//
// GENERATED by tools/gen_apple_cascade.py — do not edit by hand.
//
// CoreText resolves a character the system UI font lacks through a cascade
// list that is partly virtual (.AppleIndicFont, .AppleSimplifiedChineseFont,
// ...) and partly hidden (PingFang UI lives in a private framework). Rather
// than guess, mayag asked CoreText (CTFontCreateForString) which face it
// uses for every assigned codepoint, then solved for the flat first-covering
// order that reproduces those answers. Faces are matched by PostScript
// FAMILY (the name up to its last '-': variable fonts list named instances,
// so the measured index may not be a face index); the path and index are
// where the face lived when measured, tried first.
#include <array>
#include <cstdint>
#include <span>
#include <string_view>

namespace mayag::typo::system::apple {

struct CascadeEntry {
    std::string_view postscript;
    std::string_view path;
    std::uint32_t    face_index;
    /// Non-empty: serve ONLY these codepoint ranges [lo, hi]. Stand-ins for
    /// faces mayag cannot read (PingFang UI's `hvgl`) are limited to what
    /// CoreText drew from the original, so they never steal Yi or Mongolian.
    std::span<const std::array<char32_t, 2>> only;
};

''')
for ps, rs in limits.items():
    ident = 'only_' + ''.join(ch if ch.isalnum() else '_' for ch in ps)
    out.write(f'inline constexpr std::array<char32_t, 2> {ident}[] = {{\n')
    for i in range(0, len(rs), 6):
        out.write('    ' + ' '.join(f'{{0x{a:X}, 0x{b:X}}},' for a, b in rs[i:i + 6]) + '\n')
    out.write('};\n\n')
out.write('''inline constexpr CascadeEntry ui_cascade[] = {
''')
for ps, idx, path in rows:
    lim = ('only_' + ''.join(ch if ch.isalnum() else '_' for ch in ps)) if ps in limits else '{}'
    out.write(f'    {{"{ps}", "{path}", {idx}, {lim}}},\n')
out.write('};\n\n')
exc = json.load(open(sys.argv[4])) if len(sys.argv) > 4 and os.path.exists(sys.argv[4]) else []
out.write('''/// Codepoint ranges [lo, hi] CoreText serves from a face OTHER than the first
/// covering one in ui_cascade (Braille from Apple Braille, Hebrew points from
/// SF Hebrew, ...): `entry` indexes ui_cascade. Sorted by lo.
struct CascadeException { char32_t lo, hi; std::uint16_t entry; };
inline constexpr CascadeException ui_exceptions[] = {
''')
for i in range(0, len(exc), 4):
    out.write('    ' + ' '.join(f'{{0x{a:X}, 0x{b:X}, {e}}},' for a, b, e in exc[i:i + 4]) + '\n')
out.write('};\n\n}  // namespace mayag::typo::system::apple\n')
print(f'wrote {len(rows)} entries, {len(exc)} exception ranges')
